package com.hyanghae.backend.perfume.repository;

/**
 * 브랜드 목록 정렬 기준입니다. 브랜드 페이지의 정렬 칩 셋과 하나씩 맞습니다.
 *
 * <p>이름이 {@code NAME} 하나가 아닌 이유는 브랜드가 이름을 둘 갖기 때문입니다. 어느 이름으로
 * 줄을 세우는지가 값에 드러나야 합니다. 표의 컬럼은 {@code perfumes} 와 맞춰 {@code name}(영문)과
 * {@code name_ko} 그대로입니다.
 *
 * <p>셋 중 무엇을 화면에 띄울지는 프론트가 정합니다. 서버는 셋 다 받습니다.
 *
 * <p>문자열이 아니라 enum 인 이유는 정렬 문장을 미리 써 두고 고르기 위해서입니다. 요청 값을 SQL 에
 * 이어 붙이면 그대로 뚫립니다. 목록에 없는 값이 오면 Spring 이 400 으로 돌려줍니다.
 */
public enum BrandSort {

    /** 한국어 이름 가나다순입니다. 한국어 이름이 없는 브랜드는 뒤로 밀립니다. */
    NAME_KO,

    /** 영어 이름 abc 순입니다. 기본값입니다. */
    NAME_EN,

    /** 향수가 많은 순입니다. 같으면 영어 이름순으로 갈립니다. */
    PERFUME_COUNT
}
