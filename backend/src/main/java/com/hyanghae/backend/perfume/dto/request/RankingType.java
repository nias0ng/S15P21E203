package com.hyanghae.backend.perfume.dto.request;

/**
 * 향수를 인기순으로 줄 세우는 기준입니다.
 *
 * <p><b>전체 사용자 집계입니다.</b> "내가 담은 향수"가 아니라 "사람들이 담은 향수"라서 로그인이
 * 필요 없습니다. 이전 이름이 {@code shelf} 였는데 개인 진열대 필터로 읽혀 바꿨습니다.
 *
 * <p>거르기도 하고 줄도 세웁니다. 해당 기록이 하나도 없는 향수는 결과에서 빠지고, 남은 향수는
 * 기록이 많은 순으로 나갑니다. 다른 정렬은 없습니다.
 *
 * <p>기록이 없는 향수를 빼는 이유가 있습니다. 이 값이 답하는 질문이 "사람들이 많이 담은 향수가
 * 무엇인가" 라서, 아무도 담지 않은 향수를 0 건으로 뒤에 붙이면 카탈로그 전체가 향수 번호순으로
 * 따라옵니다. 사용자가 적은 동안에는 그 꼬리가 목록의 대부분을 차지합니다.
 */
public enum RankingType {

    /** 보유 중으로 담은 사람이 많은 순입니다. */
    OWNED,

    /** 보유 희망으로 담은 사람이 많은 순입니다. */
    WISH,

    /**
     * 상세 화면을 많이 열어 본 순입니다. 진열대와 무관합니다.
     *
     * <p>사람 수가 아니라 열어 본 횟수로 셉니다. 담기는 한 번의 결정이지만 보기는 관심이 쌓이는
     * 것이라, 여러 번 다시 열어 본 향수는 그만큼 앞에 오는 것이 맞다고 보았습니다.
     */
    VIEWED;

    /** 진열대 조회에 쓰는 {@code user_perfumes.ownership_status} 값입니다. */
    public String ownershipStatus() {
        return name();
    }
}
