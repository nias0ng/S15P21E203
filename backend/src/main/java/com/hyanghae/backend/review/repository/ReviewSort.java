package com.hyanghae.backend.review.repository;

/**
 * 후기 게시판 정렬 기준입니다. 화면의 정렬 칩 셋과 하나씩 맞습니다.
 *
 * <p>자유 게시판의 {@code PostSort} 와 달리 댓글 많은 순이 없습니다. 후기에는 댓글을 달지 않기
 * 때문입니다(와이어프레임 A22a — 후기는 좋아요만). 값이 겹친다고 한 enum 을 같이 쓰면, 후기에
 * 있을 수 없는 정렬을 받아 놓고 서비스에서 다시 걸러야 합니다.
 *
 * <p>문자열이 아니라 enum 인 이유는 정렬 문장을 미리 써 두고 고르기 위해서입니다. 요청 값을 SQL 에
 * 이어 붙이면 그대로 뚫립니다. 목록에 없는 값이 오면 Spring 이 400 으로 돌려줍니다.
 */
public enum ReviewSort {

    /** 최신순입니다. 기본값입니다. */
    RECENT,

    /** 조회가 많은 순입니다. 같으면 최신순으로 갈립니다. */
    VIEWS,

    /** 좋아요가 많은 순입니다. 같으면 최신순으로 갈립니다. */
    LIKES
}
