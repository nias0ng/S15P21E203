-- 브랜드에 한국어 이름과 로고를 더합니다.
--
-- 브랜드 페이지(와이어프레임 A34)가 정렬 칩 셋을 둡니다 — 한국어 이름순·영어 이름순·향수 많은 순.
-- 지금 brands 에는 이름이 한 칸뿐이고 71개가 모두 영문이라 한국어 정렬을 만들 자리가 없습니다.


-- 1. 이름을 두 칸으로 둡니다.
--
-- perfumes 가 이미 name 과 name_ko 를 나눠 두고 있어 같은 이름을 씁니다. 기존 name 은 그대로
-- 영문이고 새 칸이 한국어입니다. 옮기거나 바꾸지 않으므로 기존 데이터는 그대로입니다.
--
-- 비워 둘 수 있습니다. 71개 브랜드의 한국어 이름을 아직 아무도 채우지 않았고, 채우는 일은 별도로
-- 진행합니다. 그때까지 한국어 이름순은 비어 있는 브랜드를 뒤로 밀고 영문 이름으로 줄 세웁니다.
--
-- 유니크 제약은 영문 쪽(V5 의 uk_brands_name)과 맞춥니다. 같은 한국어 이름을 가진 브랜드가 둘이면
-- 화면에서 구분할 수 없습니다. PostgreSQL 은 NULL 을 서로 다른 값으로 보므로, 아직 비어 있는
-- 브랜드가 여럿이어도 제약에 걸리지 않습니다.
ALTER TABLE brands
    ADD COLUMN name_ko VARCHAR(100);

ALTER TABLE brands
    ADD CONSTRAINT uk_brands_name_ko UNIQUE (name_ko);


-- 2. 로고 주소입니다.
--
-- 화면이 카드마다 로고를 그리고, 없으면 "로고" 글자를 대신 보여줍니다. 주소만 받습니다 —
-- 게시글 이미지와 같은 방식이고, 파일을 올리는 방법은 아직 정해지지 않았습니다.
--
-- 지금은 전부 비어 있습니다. 채우기 전까지 화면은 자리표시자를 그립니다.
ALTER TABLE brands
    ADD COLUMN logo_url VARCHAR(500);


-- 3. 이름 정렬 인덱스입니다.
--
-- 한국어 정렬에 COLLATE "C" 를 씁니다. 인덱스도 같은 collation 이어야 정렬에 쓰입니다. 다르면
-- 데이터베이스가 인덱스를 건너뛰고 매번 다시 줄을 세웁니다.
--
-- "C" 는 코드포인트 순인데, 완성형 한글(U+AC00~U+D7A3)이 초성→중성→종성 순으로 배열되어 있어
-- 그것이 곧 가나다순입니다. 데이터베이스 기본값인 en_US.utf8 은 한글 규칙이 없어 '디올' 뒤에
-- '딥디크' 가 아니라 '하늘' 뒤에 '딥디크' 가 오는 식으로 어긋납니다.
--
-- ICU 의 "ko-x-icu" 가 언어학적으로 더 정확하지만 ICU 를 켠 빌드에서만 동작합니다. 배포 환경의
-- PostgreSQL 빌드를 아직 확인하지 못해 어디서나 되는 쪽을 골랐습니다. 한국어와 영문이 섞인
-- 이름을 제대로 줄 세울 일이 생기면 그때 바꿉니다.
--
-- 영문 이름은 기본 collation 그대로입니다. "C" 로 두면 대문자가 전부 앞으로 가서 'Zara' 가
-- 'adidas' 보다 앞에 옵니다. 기본값은 대소문자를 무시하고 'Bentley' 다음에 'BMW Fragrances' 를
-- 놓아 사람이 기대하는 순서를 냅니다.
CREATE INDEX idx_brands_name_ko ON brands (name_ko COLLATE "C");

CREATE INDEX idx_brands_name ON brands (name);


-- 4. 같은 브랜드가 같은 이름을 여러 번 쓰는 것을 허용합니다.
--
-- V5 가 이 제약을 건 이유는 "적재를 다시 돌려도 중복이 생기지 않도록" 이었습니다. 그때는 향수를
-- 지목할 안정적인 번호가 없어 브랜드명과 향수명으로 맞췄습니다.
--
-- 그 전제가 V6 에서 이미 무너졌습니다. V6 가 fragrantica_id 와 그 유니크 제약을 만들면서 이렇게
-- 적어 두었습니다 — "브랜드명+향수명으로 맞추는 방법은 같은 향수가 농도 표기만 달라도 여러
-- 줄이라 정확하지 않습니다." 그 뒤로 이 제약은 할 일을 잃은 채 남아 있었습니다.
--
-- 자연어 추천이 쓰는 원본 13만 건을 넣으려니 이 제약이 1,343행을 튕겨냅니다. 농도(EDP/EDT)나
-- 출시 연도만 다른 같은 이름들입니다. 버리면 추천에는 나오는데 표에 없는 향수가 생기고, 이름에
-- 구분자를 붙이면 사용자에게 없는 이름이 보입니다. 둘 다 자료를 거짓으로 만듭니다.
--
-- 향수를 하나로 지목하는 일은 uk_perfumes_fragrantica_id 가 계속 맡습니다. 자바 코드는 이 제약에
-- 기대는 곳이 없고, 적재 스크립트의 ON CONFLICT 대상만 fragrantica_id 로 함께 옮깁니다.
ALTER TABLE perfumes
    DROP CONSTRAINT uk_perfumes_brand_name;


-- 5. 평가자 수를 담습니다.
--
-- 자연어 추천의 정렬 2순위입니다. 향 특성 세기의 합이 같을 때 이 값으로 갈립니다. 장식이 아니라
-- 평점을 쓰지 않기 위해 둔 규칙입니다 — 평점 5.00 인 향수 8,410개 중 99.8% 가 평가자 10명
-- 이하라, 평점으로 줄 세우면 한 명이 만점을 준 향수가 1위가 됩니다.
--
-- 동점이 흔합니다. 조건이 넓으면 5위 자리를 두고 수천 개가 동점이라, 이 구간에서는 사실상 이
-- 값이 순서를 정합니다. 없으면 아무거나 올라옵니다.
--
-- 이름에 출처를 적습니다. 우리 서비스에도 후기 수가 있어서 그냥 people 이나 rating_count 로
-- 두면 어느 쪽인지 알 수 없습니다. fragrantica_id 와 짝이 맞습니다.
--
-- NOT NULL DEFAULT 0 인 이유가 중요합니다. PostgreSQL 의 DESC 는 NULL 을 가장 큰 값으로 보아
-- 맨 앞에 놓습니다. 비워 두면 평가자 수를 모르는 향수가 매번 1위로 올라와, 이 규칙이 막으려던
-- 바로 그 일이 일어납니다. 0 이면 "아무도 평가하지 않았다" 라는 뜻도 맞고 자리도 맨 뒤입니다.
--
-- 측정 범위는 0 ~ 35,695 라 INTEGER 로 충분합니다. 기존 202행은 0 으로 채워지고, 기본값이 있는
-- 컬럼 추가는 PostgreSQL 11 부터 표를 다시 쓰지 않아 곧바로 끝납니다.
--
-- 인덱스는 만들지 않습니다. 정렬 2순위라 이 컬럼만으로는 받지 못하고, 1순위가 계산값이라 어차피
-- 전부 줄을 세워야 합니다. 실제로 느려지면 그때 조합을 보고 만듭니다.
ALTER TABLE perfumes
    ADD COLUMN fragrantica_rating_count INTEGER NOT NULL DEFAULT 0;
