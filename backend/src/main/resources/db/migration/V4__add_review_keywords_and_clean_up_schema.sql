-- 1. 후기 키워드 통계
-- AI 가 후기에서 뽑은 향 표현을 담습니다. 계절 평가(perfume_review_seasons)와 같은 구조라
-- 집계 방식도 같습니다. 비슷한 표현을 하나로 묶는 일은 추출 단계에서 같은 keyword_id 로
-- 매핑하는 것으로 처리합니다.
CREATE TABLE review_keywords (
    keyword_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    CONSTRAINT uk_review_keywords_name UNIQUE (name)
);

CREATE TABLE perfume_review_keywords (
    review_id  BIGINT NOT NULL,
    keyword_id BIGINT NOT NULL,
    PRIMARY KEY (review_id, keyword_id),
    CONSTRAINT fk_perfume_review_keywords_review
        FOREIGN KEY (review_id) REFERENCES perfume_reviews (id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_review_keywords_keyword
        FOREIGN KEY (keyword_id) REFERENCES review_keywords (keyword_id) ON DELETE RESTRICT
);

-- 2. 후기 보류 개념 폐기
-- 후기는 존재하거나 삭제되거나 둘 중 하나이고 그 사이 상태가 없습니다.
ALTER TABLE perfume_reviews
    DROP COLUMN status,
    DROP COLUMN hold_reason;

-- 3. 게시글 보류 기능 삭제
ALTER TABLE posts
    DROP COLUMN status,
    DROP COLUMN hold_reason;

-- 4. 한 사용자는 한 향수에 후기를 하나만 가집니다.
-- 애플리케이션 검사만으로는 동시 요청에 뚫립니다. user_id 가 NULL 인 행(탈퇴한 사용자의 후기)은
-- PostgreSQL 이 NULL 을 서로 다른 값으로 보므로 이 제약에 걸리지 않습니다.
ALTER TABLE perfume_reviews
    ADD CONSTRAINT uk_perfume_reviews_user_perfume UNIQUE (user_id, perfume_id);

-- 7. 조회 인덱스
-- PostgreSQL 은 외래키에 인덱스를 자동으로 만들지 않습니다. 아래 컬럼들은 조회의 출발점인데
-- 인덱스가 없어 매 요청이 전체 스캔이었습니다.
-- 복합 기본키의 선두 컬럼으로 이미 찾을 수 있는 것(perfume_notes, perfume_accords,
-- perfume_neighbors 의 perfume_id 등)은 넣지 않았습니다.
CREATE INDEX idx_post_perfumes_perfume ON post_perfumes (perfume_id);
CREATE INDEX idx_perfume_images_perfume ON perfume_images (perfume_id);
CREATE INDEX idx_perfume_reviews_perfume ON perfume_reviews (perfume_id);
CREATE INDEX idx_perfume_prices_perfume ON perfume_prices (perfume_id);
CREATE INDEX idx_perfume_review_seasons_season ON perfume_review_seasons (season_id);
CREATE INDEX idx_user_perfumes_user ON user_perfumes (user_id);
CREATE INDEX idx_user_perfume_views_user ON user_perfume_views (user_id);
