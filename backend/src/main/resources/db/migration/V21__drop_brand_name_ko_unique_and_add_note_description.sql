-- 브랜드 한국어 이름의 UNIQUE 제약을 뗍니다.
--
-- 서로 다른 브랜드가 같은 한국어 이름을 쓰는 경우가 21그룹 44개 있습니다. 리들(Lidl / Riddle),
-- 노이즈(Noyz / Noise), 엘리시움(Elisium / Elysium) 처럼 실제로 다른 브랜드라 합칠 수 없습니다.
--
-- 제약 때문에 적재가 실패하는 것이 아니라, 적재 스크립트가 제약에 걸리지 않으려고 중복 한글명을
-- 스스로 건너뛰고 있었습니다. 그 결과 해당 브랜드의 name_ko 가 영구히 비어 화면에 영문명만
-- 나오고, 한국어 이름순 정렬에서도 NULLS LAST 로 밀려납니다.
--
-- ⚠ 이 마이그레이션만으로는 증상이 그대로입니다. db/seed/load_perfume_catalog.sql 의 건너뛰는
-- 조건을 함께 걷어내야 값이 실제로 채워집니다. 두 변경은 같은 작업에 들어 있습니다.
--
-- 남는 것들:
--   uk_brands_name      영문 이름 UNIQUE (V5). 식별자 역할은 계속 이쪽이 맡습니다.
--                       CSV 7,871행 기준 영문명 중복은 0건입니다.
--   idx_brands_name_ko  한국어 가나다순 정렬용 인덱스 (V14). UNIQUE 제약이 만든 인덱스와
--                       별개라 함께 지워지지 않습니다. 정렬 성능에 손실이 없습니다.
--
-- name_ko 를 식별 키로 쓰는 코드가 없어 애플리케이션 변경이 없습니다. 브랜드 단건 조회는
-- PK(brand_id)이고, 검색은 ILIKE 부분일치로 목록을 돌려줍니다.
--
-- 되돌리려면 제약을 다시 걸어야 하는데, 중복이 적재된 뒤에는 그 행들의 name_ko 를 먼저
-- 비워야 성공합니다. 드롭 전에 brands 의 brand_id · name · name_ko 를 백업해 두십시오.
ALTER TABLE brands
    DROP CONSTRAINT uk_brands_name_ko;

