-- 노트 설명입니다.
--
-- 노트 상세 화면이 "이 향이 어떤 향인지" 를 문장으로 보여줍니다. 지금은 이름 · 대분류 ·
-- 이미지뿐이라 화면에 적을 것이 없습니다.
--
-- 길이를 제한하지 않습니다. 몇 문장짜리 설명이고 길이가 정해진 값이 아닙니다. VARCHAR(n) 으로
-- 잡으면 n 을 넘기는 설명에서 적재가 실패하는데, 그 한계를 지금 정할 근거가 없습니다.
--
-- 비어 있을 수 있습니다. 노트가 수백 개인데 설명은 채워지는 대로 들어옵니다. NOT NULL 로 두면
-- 설명이 없는 노트를 넣을 수 없어 적재가 막힙니다. 화면은 비면 설명 영역을 그리지 않습니다.
--
-- 목록에는 내보내지 않습니다. 활성 노트 전체를 한 번에 돌려주는 응답이라 설명까지 실으면
-- 목록이 크게 무거워집니다. 상세에서만 나갑니다.
-- ---------------------------------------------------------------------------
