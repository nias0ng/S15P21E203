CREATE TABLE collection_perfumes (
    collection_id BIGINT NOT NULL,
    user_perfume_id BIGINT NOT NULL,
    display_order INTEGER,
    created_at TIMESTAMPTZ,
    PRIMARY KEY (collection_id, user_perfume_id),
