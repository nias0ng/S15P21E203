CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE TABLE brands (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE notes (
    note_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE accords (
    accord_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE seasons (
    season_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30),
    name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE scent_regions (
    scent_region_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    code VARCHAR(30) NOT NULL,
    min_x DOUBLE PRECISION,
    min_y DOUBLE PRECISION,
    max_x DOUBLE PRECISION,
    max_y DOUBLE PRECISION,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE post_categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30),
    name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE map_interaction_types (
    type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_value VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE perfumes (
    perfume_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id BIGINT,
    name VARCHAR(255),
    name_ko VARCHAR(255),
    gender VARCHAR(30),
    description VARCHAR(500),
    concentration VARCHAR(30),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_perfumes_brand
        FOREIGN KEY (brand_id) REFERENCES brands (brand_id) ON DELETE RESTRICT
);

CREATE TABLE perfume_prices (
    price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT,
    price_range NUMERIC(12, 2),
    collected_at TIMESTAMPTZ,
    volume_ml NUMERIC(6, 2),
    CONSTRAINT fk_perfume_prices_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE
);

CREATE TABLE perfume_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfume_id BIGINT,
    image_url TEXT,
    display_order INTEGER,
    CONSTRAINT fk_perfume_images_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE
);

CREATE TABLE perfume_notes (
    perfume_id BIGINT NOT NULL,
    note_id BIGINT NOT NULL,
    note_type VARCHAR(30),
    PRIMARY KEY (perfume_id, note_id),
    CONSTRAINT fk_perfume_notes_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_notes_note
        FOREIGN KEY (note_id) REFERENCES notes (note_id) ON DELETE RESTRICT
);

CREATE TABLE perfume_accords (
    perfume_id BIGINT NOT NULL,
    accord_id BIGINT NOT NULL,
    rank INTEGER,
    weight NUMERIC(10, 6),
    PRIMARY KEY (perfume_id, accord_id),
    CONSTRAINT fk_perfume_accords_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_accords_accord
        FOREIGN KEY (accord_id) REFERENCES accords (accord_id) ON DELETE RESTRICT
);

CREATE TABLE perfume_neighbors (
    perfume_id BIGINT NOT NULL,
    neighbor_perfume_id BIGINT NOT NULL,
    PRIMARY KEY (perfume_id, neighbor_perfume_id),
    CONSTRAINT fk_perfume_neighbors_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_neighbors_neighbor
        FOREIGN KEY (neighbor_perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE
);

CREATE TABLE perfume_map_points (
    perfume_id BIGINT PRIMARY KEY,
    scent_region_id BIGINT NOT NULL,
    map_x DOUBLE PRECISION,
    map_y DOUBLE PRECISION,
    CONSTRAINT fk_perfume_map_points_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_map_points_scent_region
        FOREIGN KEY (scent_region_id) REFERENCES scent_regions (scent_region_id) ON DELETE RESTRICT
);

CREATE TABLE perfume_review_summaries (
    perfume_id BIGINT PRIMARY KEY,
    summary_text TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    source_review_count INTEGER,
    CONSTRAINT fk_perfume_review_summaries_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE CASCADE
);

CREATE TABLE posts (
    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    category_id BIGINT,
    title VARCHAR(50),
    content TEXT,
    status VARCHAR(30),
    hold_reason VARCHAR(500),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT fk_posts_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_posts_category
        FOREIGN KEY (category_id) REFERENCES post_categories (category_id) ON DELETE RESTRICT
);

CREATE TABLE post_images (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT,
    image_url TEXT,
    display_order INTEGER,
    CONSTRAINT fk_post_images_post
        FOREIGN KEY (post_id) REFERENCES posts (post_id) ON DELETE CASCADE
);

CREATE TABLE post_perfumes (
    post_id BIGINT NOT NULL,
    perfume_id BIGINT NOT NULL,
    display_order INTEGER,
    PRIMARY KEY (post_id, perfume_id),
    CONSTRAINT fk_post_perfumes_post
        FOREIGN KEY (post_id) REFERENCES posts (post_id) ON DELETE CASCADE,
    CONSTRAINT fk_post_perfumes_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE RESTRICT
);

CREATE TABLE comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT,
    user_id BIGINT,
    content TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT fk_comments_post
        FOREIGN KEY (post_id) REFERENCES posts (post_id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE TABLE perfume_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    perfume_id BIGINT,
    title VARCHAR(100),
    content TEXT,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    status VARCHAR(30),
    hold_reason VARCHAR(500),
    CONSTRAINT fk_perfume_reviews_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_perfume_reviews_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE RESTRICT
);

CREATE TABLE perfume_review_seasons (
    review_id BIGINT NOT NULL,
    season_id BIGINT NOT NULL,
    PRIMARY KEY (review_id, season_id),
    CONSTRAINT fk_perfume_review_seasons_review
        FOREIGN KEY (review_id) REFERENCES perfume_reviews (id) ON DELETE CASCADE,
    CONSTRAINT fk_perfume_review_seasons_season
        FOREIGN KEY (season_id) REFERENCES seasons (season_id) ON DELETE RESTRICT
);

CREATE TABLE user_perfumes (
    user_perfumes_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    perfume_id BIGINT,
    ownership_status VARCHAR(30),
    fit_rating NUMERIC(2, 1),
