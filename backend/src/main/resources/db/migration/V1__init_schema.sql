    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT fk_user_perfumes_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_perfumes_perfume
        FOREIGN KEY (perfume_id) REFERENCES perfumes (perfume_id) ON DELETE RESTRICT
);

CREATE TABLE personal_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_perfume_id BIGINT,
    content TEXT,
    tested_at DATE,
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT fk_personal_records_user_perfume
        FOREIGN KEY (user_perfume_id) REFERENCES user_perfumes (user_perfumes_id) ON DELETE CASCADE
);

CREATE TABLE collections (
    collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
