CREATE TABLE user_preference_regions (
    region_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    center_x DOUBLE PRECISION,
    center_y DOUBLE PRECISION,
    PRIMARY KEY (region_id, user_id),
