    name VARCHAR(255),
    description VARCHAR(500),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ,
    CONSTRAINT fk_collections_user
        FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
