-- nlr_* 표의 주석 셋을 고칩니다. 구조는 건드리지 않습니다.
--
-- 왜 V23 을 고치지 않고 새 파일인가 — V23 은 이미 병합돼 적용된 마이그레이션입니다.
-- 주석 한 글자만 바꿔도 체크섬이 달라지고, Flyway 의 validateOnMigrate 가 이미 V23 을
-- 적용한 모든 DB 에서 기동을 막습니다. 배포 서버와 팀원 로컬이 전부 걸립니다.
-- 적용된 마이그레이션은 고치지 않고 덧붙입니다.

-- ---------------------------------------------------------------------------
-- 1. "AI 응답에 이 값이 추가되면 NOT NULL 로 올릴 것" — 이제 추가됐습니다.
--
-- had_conditions 는 값이 오기 시작했습니다. 그래도 NOT NULL 로 올리지 않습니다.
-- V23 이 배포된 뒤 AI 가 보내기 전까지 쌓인 줄이 이미 NULL 이라, 올리면 그 줄들 때문에
-- 마이그레이션 자체가 실패합니다. 지난 기록을 지우면서까지 제약을 얻을 이유가 없습니다.
-- ---------------------------------------------------------------------------
COMMENT ON COLUMN nlr_unmatched_expressions.had_conditions IS
    '그 요청이 향 조건을 뽑았는가. NULL 은 모른다는 뜻 — AI 가 보내기 전에 쌓인 줄이다';

-- ---------------------------------------------------------------------------
-- 2. lexicon_version 은 NOT NULL 로 올리면 안 됩니다.
--
-- 지시와 구현이 반대였습니다. AI 는 사전 파일 이름이 규칙에 안 맞을 때(측정용 임시 파일
-- 등) **의도적으로 null 을 보냅니다.** 그 null 은 "없다" 가 아니라 "모른다" 이고, 우리는
-- 추측해서 채우지 않기로 했습니다 — 틀린 값은 칸이 비어 있는 것보다 나쁩니다. 비어 있으면
-- 모른다는 것을 알지만, 틀리면 아는 줄 착각합니다.
--
-- NOT NULL 로 올리면 그 요청의 기록이 통째로 실패하고, 기록 실패는 추천을 막지 않으므로
-- 화면은 멀쩡한데 집계만 조용히 빕니다.
-- ---------------------------------------------------------------------------
COMMENT ON COLUMN nlr_recommendations.lexicon_version IS
    '엔진이 쓴 향 사전 버전(v1_15). AI 가 모르면 null 이다 — NOT NULL 로 올리지 말 것';

COMMENT ON COLUMN nlr_recommendations.prompt_sha256 IS
    '①단계 프롬프트 지문 앞 16자. AI 가 못 읽으면 null 이다 — NOT NULL 로 올리지 말 것';

-- ---------------------------------------------------------------------------
-- 3. result_count 가 두 수 중 무엇인지 적습니다.
--
-- AI 가 찾은 개수입니다. 사용자가 본 개수가 아닙니다. 둘은 실제로 갈립니다 — AI 는 자기
-- 데이터 13만 개에서 찾는데 그 향수가 우리 DB 에 없으면 화면에 안 나갑니다.
--
-- 왜 AI 기준인가 — 이 칸이 답하는 질문이 "⑤단계 추정이 결과를 만들었나" 이고, 그것은
-- AI 색인 안의 일입니다. 우리 적재가 밀린 것을 섞으면 추정이 실제보다 나빠 보입니다.
--
-- 사용자가 본 개수는 잃지 않습니다. nlr_recommendation_items 의 줄 수가 그 값입니다.
-- 둘이 벌어진 줄은 버그가 아니라 **적재가 밀렸다는 신호**입니다.
-- ---------------------------------------------------------------------------
COMMENT ON COLUMN nlr_unmatched_expressions.result_count IS
    'AI 가 찾은 추천 개수(사용자가 본 개수가 아니다 — 그것은 nlr_recommendation_items 줄 수).'
    ' 추정을 물어봤을 때만 값이 있다';
