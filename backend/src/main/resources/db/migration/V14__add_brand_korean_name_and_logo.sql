-- 브랜드에 한국어 이름과 로고를 더합니다.
--
-- 브랜드 페이지(와이어프레임 A34)가 정렬 칩 셋을 둡니다 — 한국어 이름순·영어 이름순·향수 많은 순.
-- 지금 brands 에는 이름이 한 칸뿐이고 71개가 모두 영문이라 한국어 정렬을 만들 자리가 없습니다.


-- 1. 이름을 두 칸으로 둡니다.
--
-- perfumes 가 이미 name 과 name_ko 를 나눠 두고 있어 같은 이름을 씁니다. 기존 name 은 그대로
-- 영문이고 새 칸이 한국어입니다. 옮기거나 바꾸지 않으므로 기존 데이터는 그대로입니다.
--
-- 비워 둘 수 있습니다. 71개 브랜드의 한국어 이름을 아직 아무도 채우지 않았고, 채우는 일은 별도로
-- 진행합니다. 그때까지 한국어 이름순은 비어 있는 브랜드를 뒤로 밀고 영문 이름으로 줄 세웁니다.
--
-- 유니크 제약은 영문 쪽(V5 의 uk_brands_name)과 맞춥니다. 같은 한국어 이름을 가진 브랜드가 둘이면
-- 화면에서 구분할 수 없습니다. PostgreSQL 은 NULL 을 서로 다른 값으로 보므로, 아직 비어 있는
-- 브랜드가 여럿이어도 제약에 걸리지 않습니다.
ALTER TABLE brands
    ADD COLUMN name_ko VARCHAR(100);

ALTER TABLE brands
    ADD CONSTRAINT uk_brands_name_ko UNIQUE (name_ko);


-- 2. 로고 주소입니다.
--
-- 화면이 카드마다 로고를 그리고, 없으면 "로고" 글자를 대신 보여줍니다. 주소만 받습니다 —
-- 게시글 이미지와 같은 방식이고, 파일을 올리는 방법은 아직 정해지지 않았습니다.
--
-- 지금은 전부 비어 있습니다. 채우기 전까지 화면은 자리표시자를 그립니다.
ALTER TABLE brands
    ADD COLUMN logo_url VARCHAR(500);


-- 3. 이름 정렬 인덱스입니다.
--
-- 한국어 정렬에 COLLATE "C" 를 씁니다. 인덱스도 같은 collation 이어야 정렬에 쓰입니다. 다르면
-- 데이터베이스가 인덱스를 건너뛰고 매번 다시 줄을 세웁니다.
--
-- "C" 는 코드포인트 순인데, 완성형 한글(U+AC00~U+D7A3)이 초성→중성→종성 순으로 배열되어 있어
-- 그것이 곧 가나다순입니다. 데이터베이스 기본값인 en_US.utf8 은 한글 규칙이 없어 '디올' 뒤에
-- '딥디크' 가 아니라 '하늘' 뒤에 '딥디크' 가 오는 식으로 어긋납니다.
--
-- ICU 의 "ko-x-icu" 가 언어학적으로 더 정확하지만 ICU 를 켠 빌드에서만 동작합니다. 배포 환경의
-- PostgreSQL 빌드를 아직 확인하지 못해 어디서나 되는 쪽을 골랐습니다. 한국어와 영문이 섞인
-- 이름을 제대로 줄 세울 일이 생기면 그때 바꿉니다.
--
-- 영문 이름은 기본 collation 그대로입니다. "C" 로 두면 대문자가 전부 앞으로 가서 'Zara' 가
-- 'adidas' 보다 앞에 옵니다. 기본값은 대소문자를 무시하고 'Bentley' 다음에 'BMW Fragrances' 를
-- 놓아 사람이 기대하는 순서를 냅니다.
CREATE INDEX idx_brands_name_ko ON brands (name_ko COLLATE "C");

CREATE INDEX idx_brands_name ON brands (name);
