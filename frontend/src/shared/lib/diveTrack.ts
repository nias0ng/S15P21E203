export const RISE_ENGINE_FROM = 0.8

/**
 * **떠오를 때** 메인을 기다리는 상한(ms) — 2026-09-19 · ⭐ 2026-09-20 : 5000 → **2500**.
 *
 * 돌아가는 길은 기다리는 것이 목록이 아니라 **3D 엔진**입니다. 첫 진입 때 받아 둔 것을 쓰므로
 * 늘 재진입이고, 실측하니 클릭에서 엔진이 설 때까지 **약 2.4초**였습니다 (목데이터 개발 서버 ·
 * 에셋 캐시 있음 · 로딩 커튼이 걷기 시작하는 때 기준).
 *
 * ⭐⭐ **맞바꿈을 뒤집었습니다.** 5000 은 *엔진을 끝까지 기다린다* 는 쪽이었습니다 — 상한에 걸려
 *   걷으면 엔진이 아직 안 선 바다가 드러나므로, 실측 2.4초보다 두 배 넉넉히 뒀습니다. 그런데
 *   돌아오는 길이 화면 **다섯**에 걸리면서 그 안전이 비싸졌습니다 : 엔진이 늦는 날 로고를 누르면
 *   **5초 동안 아무 일도 안 일어나는 판**을 보게 되고, 다섯 곳에서 그렇습니다.
 *   그래서 실측(2.4초)보다 **살짝 길게**만 둬서, 그보다 늦으면 커튼이 **먼저 걷히게** 합니다.
 *
 * ⚠ 그래서 엔진이 덜 선 채로 드러나는 장이 생깁니다 — 받아들인 대가입니다. 다만 그 자리는 흰
 *   화면이 아니라 `--color-surface-night`(= navy, 커튼의 가장 깊은 색)이고, 엔진이 서는 순간
 *   걷는 중이던 루프가 이어서 밀기 때문에(`DiveCurtain` 의 걷힘 tick 이 매 장 `engine?.()` 을
 *   다시 집습니다) **늦게 뜬 엔진도 남은 걷힘에 올라탑니다.** 멈춤보다 이쪽이 낫습니다.
 * ⚠ 나가는 길의 상한(`READY_CAP_MS` 2600)과 비슷한 값이 된 것은 우연입니다 — 기다리는 것이
 *   서로 다르므로(엔진 · 목록) 따로 둡니다.
 */
export const RISE_CAP_MS = 2500

/**
 * 움직임 줄이기(`prefers-reduced-motion`)일 때의 잠수 시간(ms).
 * 카메라 잠수를 빼고 커튼만 짧게 덮습니다 (문서 §4-2 의 마지막 줄).
 */
export const REDUCED_MS = 200

/** 이 프로젝트의 집 커브 — 엔진 `phase.js` 의 `inOutCubic` 과 같은 식입니다 */
export const inOutCubic = (t: number): number =>
  t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2

/**
 * 커튼이 차오르는 커브 — **느리게 시작해 끝에서 삼킨다** (2026-09-18).
 *
 * ⚠⚠ 집 커브(`inOutCubic`)를 안 쓰는 자리입니다. 커튼이 `scaleY` 로 아래끝에서 자라게 되면서
 * (`dive-curtain.css` 머리말) 번짐이 **차오름 0.44 만에 화면 꼭대기에 닿습니다** — 판을 밀어
 * 올리던 때보다 훨씬 빨리 덮입니다. 가운데가 빠른 `inOutCubic` 을 그대로 두면 잠수 중반에
 * 이미 3D 가 안 보여서, **카메라가 내려가는 것 자체를 못 봅니다.**
 *
 * `t²` 는 앞을 비워 3D 를 오래 보여 주고 뒤에서 빠르게 삼킵니다 (차오름이 화면 꼭대기에 닿는
 * 때 : `inOutCubic` k 0.65 → **k 0.76**).
 */
const coverEase = (t: number): number => t * t

export interface DiveFrame {
  /** 엔진에 넘기는 진행도 0~1 (1 = 화면을 다 덮은 순간) */
  k: number
  /** 커튼이 차오른 정도 0~1 (1 = 화면 전체가 짙은 바다색) */
  cover: number
  /** 다 덮었는가 — 이때 간 화면으로 옮겨 갑니다 */
  covered: boolean
}

/**
 * 잠수 시작에서 `elapsed` ms 지난 지금의 값.
 *
 * ⚠ `cover` 는 `k` 를 그대로 쓰지 않습니다 — `COVER_FROM` 부터 시작해 **같은 1.0 에서 끝납니다.**
 *   두 값을 하나로 합치면 커튼이 3D 보다 먼저 올라오거나 늦게 닿습니다.
 */
export function diveFrameAt(elapsed: number, duration = DIVE_MS): DiveFrame {
  const k = clamp01(elapsed / Math.max(1, duration))
  const cover = coverEase(clamp01((k - COVER_FROM) / (1 - COVER_FROM)))
  return { k, cover, covered: k >= 1 }
}

/**
 * 이번 전환에 쓰는 시간(ms).
 *
 * 움직임 줄이기면 3D 를 안 건드리고 커튼만 짧게 덮습니다 — 그때는 **깊이를 안 봅니다.**
 * 깊이는 '내려가는 동안' 을 길게 하는 값이고, 여기는 내려가는 것 자체를 뺀 자리입니다.
 */
export function diveDuration(reducedMotion: boolean, depth = 0): number {
  return reducedMotion ? REDUCED_MS : diveMsAt(depth)
}
