/**
 * 획 길이 → 획마다 언제 · 얼마나 자랄지. 길이에 그대로 비례시키면 긴 세로획이 너무 오래 걸리므로
 * `lengthPower`(기본 0.55)로 차이를 누릅니다. 획 사이의 숨도 `drawMs` 안에 들어가 전체가 정확히 `drawMs` 에 끝납니다.
 */
export function wordmarkTrim(
  lengths: readonly number[],
  { drawMs, strokeGapMs = 0, lengthPower = 0.55 }: WordmarkTiming,
): WordmarkTrim[] {
  if (lengths.length === 0) return []
  const weights = lengths.map((length) => Math.max(0, length) ** lengthPower)
  const total = weights.reduce((sum, weight) => sum + weight, 0)
  const gaps = (lengths.length - 1) * strokeGapMs
  const span = Math.max(0, drawMs - gaps)
  const steps: WordmarkTrim[] = []
  let drawn = 0
  weights.forEach((weight, stroke) => {
    const share = total > 0 ? weight / total : 1 / weights.length
    steps.push({
      delay: drawn * span + stroke * strokeGapMs,
      duration: share * span,
    })
    drawn += share
  })
  return steps
}

/** 마지막 획까지 다 그려지는 시각(ms) — `lag` 이 있으면 그만큼 늦게 따라오는 겹까지 셉니다 */
export function wordmarkDrawnAt(
  steps: readonly WordmarkTrim[],
  lag = 0,
): number {
  return steps.reduce(
    (last, step) => Math.max(last, step.delay + step.duration * (1 + lag)),
    0,
  )
}

/**
 * 획이 나가는 결 — **빠르게 튀어 나갔다 사뿐히 멎습니다**(out cubic).
 * 사용자 (2026-09-18) : *"패스가 진행되는 값을 좀 더 날카롭게"* — 사인 인아웃은 시작이 물러 붓이 뭉툭해 보였습니다.
 */
export const wordmarkEase = (t: number): number =>
  1 - (1 - Math.min(1, Math.max(0, t))) ** 3

/**
 * 지금 획마다 얼마나 그려졌는지 (0 ~ 1). `stroke-dashoffset` 은 `길이 × (1 − 이 값)` 입니다.
 *
 * `drawn` 은 흐른 시간이 아니라 **그려진 장만큼 흐른 시계**입니다 (SceneBootCurtain). 엔진이 메인 스레드를 막는
 * 동안에는 장이 안 나오므로 시계도 서고, 막힘이 풀리면 멈춘 자리에서 이어 그립니다 — 시간으로 재면 막힌 사이에
 * 획이 훌쩍 건너뛰어 그리는 모습이 통째로 사라집니다.
 *
 * `lag` 은 이 겹이 붓끝보다 얼마나 뒤처지는지 — **그 획을 그리는 시간에 대한 몫**입니다(0.6 이면 획 하나 그리는
 * 시간의 0.6 만큼 뒤). 시간(ms)이 아니라 몫이라 짧은 획은 짧게, 긴 획은 길게 뒤처집니다 — 그래서 획 머리의
 * 가는 자국이 **획 길이에 맞춰 길게** 남습니다. 붓끝이 획 끝에 닿은 뒤에도 뒤엣것이 마저 따라와 제 굵기가 됩니다.
 */
export function wordmarkProgress(
  steps: readonly WordmarkTrim[],
  drawn: number,
  lag = 0,
): number[] {
  return steps.map((step) => {
    const t =
      step.duration > 0
        ? (drawn - step.delay) / step.duration - lag
        : drawn >= step.delay
          ? 1
          : 0
    return wordmarkEase(t)
  })
}
